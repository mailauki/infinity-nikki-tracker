import { ColorTheme } from './types/eureka'

/**
 * An M3 tonal color role: the accent itself, the content drawn on top of it,
 * and the low-emphasis container pair. Names mirror the M3 tokens with the
 * role prefix dropped — `primary.on` is `on-primary`, `primary.onContainer`
 * is `on-primary-container`.
 */
export interface M3ColorRole {
  main: string
  on: string
  container: string
  onContainer: string
}

/**
 * The M3 surface roles. `main` is `surface`; `dim`/`bright` are its two
 * fixed extremes; `containerLowest` → `containerHighest` is the five-step
 * container ladder that replaced elevation overlays in M3. `on`/`onVariant`
 * are the content tones, `variant` the muted fill, and `inverse`/`inverseOn`
 * the reversed pair used by snackbars and tooltips.
 */
export interface M3SurfaceRoles {
  main: string
  dim: string
  bright: string
  containerLowest: string
  containerLow: string
  container: string
  containerHigh: string
  containerHighest: string
  on: string
  onVariant: string
  variant: string
  inverse: string
  inverseOn: string
}

/**
 * One complete M3 scheme. Everything MUI needs is derived from these tokens in
 * `buildColorSchemes` — `background` and `text` come from the surface roles and
 * `divider` from `outlineVariant`, so a preset never states the same color twice.
 */
export interface M3ColorScheme {
  primary: M3ColorRole
  secondary: M3ColorRole
  tertiary: M3ColorRole
  error: M3ColorRole
  /** Not an M3 role. Kept because the app uses MUI's `color="success"`. */
  success: M3ColorRole
  surface: M3SurfaceRoles
  outline: string
  outlineVariant: string
  inversePrimary: string
}

export interface ColorThemePreset {
  label: string
  description: string
  light: M3ColorScheme
  dark: M3ColorScheme
}

