/** MUI wants `contrastText`; M3 calls the same token `on-<role>`. */
function paletteColor(role: M3ColorRole) {
  return {
    main: role.main,
    contrastText: role.on,
    on: role.on,
    container: role.container,
    onContainer: role.onContainer,
  }
}

function buildPalette(scheme: M3ColorScheme) {
  return {
    primary: paletteColor(scheme.primary),
    secondary: paletteColor(scheme.secondary),
    tertiary: paletteColor(scheme.tertiary),
    error: paletteColor(scheme.error),
    success: paletteColor(scheme.success),
    surface: scheme.surface,
    outline: scheme.outline,
    outlineVariant: scheme.outlineVariant,
    inversePrimary: scheme.inversePrimary,
    // M3 folded `background` into `surface`; MUI still reads both, so they
    // point at the same token rather than drifting apart.
    background: { default: scheme.surface.main, paper: scheme.surface.main },
    text: { primary: scheme.surface.on, secondary: scheme.surface.onVariant },
    divider: scheme.outlineVariant,
  }
}

export function buildColorSchemes(preset: ColorThemePreset) {
  return {
    light: { palette: buildPalette(preset.light) },
    dark: { palette: buildPalette(preset.dark) },
  }
}
